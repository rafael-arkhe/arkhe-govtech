import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync,readFileSync,appendFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { DatabaseSync } from 'node:sqlite';
process.env.GOVTECH_DATA_DIR=mkdtempSync(join(tmpdir(),'govtech-backup-source-'));
const base=mkdtempSync(join(tmpdir(),'govtech-backup-target-'));
execFileSync(process.execPath,['scripts/setup.mjs'],{stdio:'pipe'});
const {govState,govCreate}=await import('../lib/govtech.mjs');
const user={id:'owner',role:'owner'};govState(user);
const c=govCreate(user,{agency:'inovacao',kind:'atendimento',title:'Proposta de backup sintético',reference:'BACKUP-TEST',body:'Somente teste de persistência e restauração.',sourceDigest:'a'.repeat(64),items:[{label:'Sem despesa',amount:0}]});
test('backup includes committed WAL state; restore verifies hashes and preserves the case',()=>{
 const target=join(base,'snapshot'),restored=join(base,'restored');
 execFileSync(process.execPath,['scripts/backup.mjs',target],{stdio:'pipe'});
 const manifest=JSON.parse(readFileSync(join(target,'manifest.json')));assert.equal(manifest.containsPrivateKeys,true);
 execFileSync(process.execPath,['scripts/restore.mjs',target,restored],{stdio:'pipe'});
 const db=new DatabaseSync(join(restored,'govtech.sqlite'));assert.equal(JSON.parse(db.prepare('SELECT value FROM gov_cases WHERE id=?').get(c.id).value).reference,'BACKUP-TEST');assert.equal(db.prepare('SELECT COUNT(*) AS n FROM sessions').get().n,0);db.close();
 assert.throws(()=>execFileSync(process.execPath,['scripts/restore.mjs',target,restored],{stdio:'pipe'}));
 appendFileSync(join(target,'accounts.json'),' ');assert.throws(()=>execFileSync(process.execPath,['scripts/restore.mjs',target,join(base,'tampered')],{stdio:'pipe'}));
});
